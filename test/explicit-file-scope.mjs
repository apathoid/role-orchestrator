import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm, writeFile, utimes, symlink } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { emptyTaskSpec,validateTaskSpec } from '../src/routing/task-spec.mjs';
import { resolveReviewScope } from '../src/review-scope.mjs';
const root=await mkdtemp(join(tmpdir(),'ro-explicit-files-'));
const external=await mkdtemp(join(tmpdir(),'ro-outside-'));
const git=(...args)=>{const result=spawnSync('git',args,{cwd:root,encoding:'utf8'});
  assert.equal(result.status,0,result.stderr);};
const spec=(paths)=>({...emptyTaskSpec('review'),target:{kind:'git',selector:{type:'files',paths}}});
try {
  git('init','-q');git('config','user.name','Fixture');git('config','user.email','fixture@example.invalid');
  await mkdir(join(root,'src'));
  await writeFile(join(root,'src','a.ts'),'A');
  git('add','.');git('commit','-qm','init');
  const task=validateTaskSpec(spec(['src/a.ts','deleted.ts']));
  const first=await resolveReviewScope(root,task);
  assert.equal(first.complete,true);
  assert.equal(first.selector,'explicit-files');
  assert.equal(first.paths.length,2);
  assert.equal(first.paths.find(row=>row.path==='deleted.ts').changes[0].fingerprint,'missing');
  assert.equal(first.paths.find(row=>row.path==='src/a.ts').changes[0].source,'explicit_files');
  await utimes(join(root,'src','a.ts'),new Date(Date.now()+10000),new Date(Date.now()+10000));
  const retouched=await resolveReviewScope(root,task);
  assert.equal(retouched.revisionKey,first.revisionKey,'metadata-only drift must not change content identity');
  await writeFile(join(root,'src','a.ts'),'B');
  const changed=await resolveReviewScope(root,task);
  assert.notEqual(changed.revisionKey,first.revisionKey,'content drift invalidates selected evidence');
  await writeFile(join(external,'secret'),'secret');
  await symlink(join(external,'secret'),join(root,'link.ts'));
  const link=await resolveReviewScope(root,spec(['link.ts']));
  assert.equal(link.status,'resolved','final symlink is inventoried as a link without opening target');
  assert.match(link.paths[0].changes[0].fingerprint,/^symlink:/);
  await symlink(external,join(root,'escaped'));
  const escape=await resolveReviewScope(root,spec(['escaped/secret']));
  assert.equal(escape.complete,false,'symlink parent cannot escape pinned workspace');
  assert.throws(()=>validateTaskSpec(spec(['/tmp/file'])),/invalid_explicit_file_paths/);
  assert.throws(()=>validateTaskSpec(spec(['../outside'])),/invalid_explicit_file_paths/);
  assert.throws(()=>validateTaskSpec(spec(['src/a.ts','src/a.ts'])),/invalid_explicit_file_paths/);
  const union=await resolveReviewScope(root,{type:'union',selectors:[{type:'files',paths:['src/a.ts']},{type:'worktree'}]});
  assert.equal(union.status,'resolved');
  assert.equal(union.paths.filter(row=>row.path==='src/a.ts').length,1,'union de-duplicates selected paths');
  console.log('explicit-file-scope: PASS');
} finally {await rm(root,{recursive:true,force:true});await rm(external,{recursive:true,force:true});}
