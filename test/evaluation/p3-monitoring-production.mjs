// Third-pass operational audit: hostile telemetry, stream races and persistence.
import assert from 'node:assert/strict';
import { createEfficiencyRun } from '../../src/efficiency/analytics.mjs';
import { normalizeEfficiencyRuns } from '../../src/session-store.mjs';
import { normalizeAgentEvent } from '../../src/providers/events.mjs';
import { efficiencyReadiness } from '../../src/efficiency/readiness.mjs';
import { profileRolePrompt,contextPart,trackedBody,unpackTrackedBody,profileTaskBody } from '../../src/efficiency/profiling.mjs';
const secret='SECRET_CONTEXT_MONITORING_PAYLOAD';
// Duplicate identical interpolations have exact source positions, even inside
// nested untagged templates. Measurements cannot change string output.
const ordinary=`parent ${`inner ${secret}`} and ${secret} and ${secret}`;
const measured=trackedBody`parent ${`inner ${contextPart('review',secret)}`} and ${contextPart('review',secret)} and ${contextPart('review',secret)}`;
const unpacked=unpackTrackedBody(measured);
assert.equal(unpacked.text,ordinary);
assert.equal(unpacked.sources.filter(s=>s.kind==='review').length,2);
const exact=profileTaskBody(unpacked.text,unpacked.sources);
assert.equal(exact.sections.find(r=>r.kind==='review').characters,secret.length*2);

const run=createEfficiencyRun('audit-pass-3');
run.onEvent({type:'role_start',invocationId:'a',role:'router',model:'fake'});
run.onEvent({type:'role_router_context',invocationId:'a',routerContext:{mode:'optimized',selected:'optimized',reason:'explicit_digest_verified',originalCharacters:10000,projectedCharacters:2000,documentsExcluded:1,raw:secret}});
run.onEvent({type:'role_provider_prompt_profile',invocationId:'a',profile:{scope:'provider_adapter_prepared_only',characters:20,utf8Bytes:20,textBlocks:1,supplementalBlocks:0,prompt:secret}});
run.onEvent({type:'role_activity',invocationId:'a',activity:'answer'});
run.onEvent({type:'role_usage',invocationId:'a',usageObservation:{semantics:'occupancy',scope:'turn'},usage:{contextUsedTokens:8000,contextWindow:30000,inputTokens:null,outputTokens:null}});
run.onEvent({type:'role_tool_event',invocationId:'a',update:{sessionUpdate:'tool_call',toolCallId:'test-call',name:'read_file',content:[{text:secret}]}});
run.onEvent({type:'role_tool_event',invocationId:'a',update:{sessionUpdate:'tool_call',toolCallId:'test-call',name:'read_file',content:[{text:secret}]}});
run.onEvent({type:'role_tool_event',invocationId:'a',update:{sessionUpdate:'tool_call_update',toolCallId:'test-call',name:'read_file',status:'completed',content:[{text:secret}]}});
run.onEvent({type:'role_done',invocationId:'a',elapsedMs:100});
run.onEvent({type:'role_usage',invocationId:'a',usage:{contextUsedTokens:88888,contextWindow:30000}});
run.onEvent({type:'role_activity',invocationId:'a',activity:'reasoning'});
const rec=run.finish({status:'completed'});
const first=rec.invocations[0];
assert.equal(first.toolCalls,1);
assert.equal(first.toolCategories.read,1,'duplicate tool call must not inflate categories');
assert.equal(first.toolCompleted,1);
assert.equal(first.contextOccupancy.peak,8000,'late usage cannot mutate completed invocation');
assert.equal(first.firstReasoningElapsedMs,null,'late activity must be ignored');
assert.equal(first.usage.inputTokens,null,'occupancy must not materialize token usage');
assert.equal(first.usageCoverage,'unknown');
assert.equal(first.usageAvailability.contextOccupancy,'observed');
assert(first.firstActivityElapsedMs<=first.elapsedMs);
assert(!JSON.stringify(rec).includes(secret));
const persisted=normalizeEfficiencyRuns([rec])[0].invocations[0];
assert.equal(persisted.routerContext.selected,'optimized');
assert.equal(persisted.timingBasis,'monotonic_invocation');
assert.equal(persisted.toolCategories.read,1);
assert(!JSON.stringify(persisted).includes(secret));
const poisoned=structuredClone(rec);
poisoned.invocations[0].routerContext.secret=secret;
poisoned.invocations[0].toolCategories={evil:100,read:1,other:1};
poisoned.invocations[0].usageAvailability.secret=secret;
poisoned.invocations[0].contextProfile=profileRolePrompt({sections:['role','context','','body',''],prompt:'role\n\ncontext\n\nbody',instructionSources:[{scope:'project',body:secret}]});
poisoned.invocations[0].contextProfile.instructionSources[0].raw=secret;
const stripped=normalizeEfficiencyRuns([poisoned]);
assert(!JSON.stringify(stripped).includes(secret));
assert.equal(stripped[0].invocations[0].contextProfile.instructionSources[0].characters,secret.length);
assert.equal(stripped[0].invocations[0].toolCategories.evil,undefined);
const readiness=efficiencyReadiness(stripped);
assert.equal(readiness.providerTokenUsage,'not_reported');
assert.equal(readiness.coverage.boundary,1);
assert.equal(readiness.coverage.occupancy,1);
assert.equal(normalizeAgentEvent({type:'prompt_profile',profile:{scope:'a'}}).type,'prompt_profile');
console.log('evaluation/p3-monitoring-production: PASS');
