// Semantic Router is the sole interpreter of natural-language task intent.
// The normalized task spec is DATA, never permission, a Git command or a scheduler.
import { canonicalTaskPath } from './task-path.mjs';
export const TASK_SPEC_VERSION = 1;
const OPERATIONS = new Set(['investigate','review','change','plan']);
const WRITE = new Set(['explicit','not_requested','ambiguous']);
const CONTINUATIONS = new Set(['new','current_review','current_implementation','saved_implementation','saved_review','information','revise_plan','reconcile','ambiguous']);
export const QUALITY_GOALS = Object.freeze(['test_inventory','scenario_assessment','executed_test_evidence','measured_code_coverage']);
const QUALITY_GOAL_SET = new Set(QUALITY_GOALS);
const SELECTORS = new Set(['recent_commits','commit','range','relative_ref','worktree','staged','unstaged','ticket_commits','files','union']);
// Only codes generated by this validator may leave the process as diagnostics.
// Never persist an arbitrary provider error.message or task field value.
export const TASK_SPEC_FAILURE_CODES = Object.freeze([
  'unsupported_task_spec_version', 'invalid_task_spec_root',
  'invalid_task_spec_operation', 'invalid_task_spec_write_intent',
  'invalid_task_spec_ambiguities', 'invalid_task_spec_target',
  'invalid_task_spec_target_kind', 'invalid_task_spec_target_selector',
  'invalid_task_spec_selector', 'invalid_task_spec_selector_type',
  'invalid_task_spec_selector_fields', 'invalid_explicit_file_paths', 'invalid_task_spec_union',
  'invalid_recent_commit_count', 'invalid_task_spec_git_ref',
  'invalid_task_spec_git_range', 'invalid_task_spec_ticket',
  'invalid_union_merge_parent', 'invalid_task_spec_merge_parent',
  'invalid_task_spec_constraints', 'invalid_task_spec_exclusions',
  'invalid_task_spec_review_depth', 'invalid_task_spec_resources',
  'invalid_task_spec_verification', 'invalid_task_spec_priorities',
  'invalid_task_spec_review_checks', 'invalid_task_spec_file_count',
  'invalid_task_spec_skill', 'invalid_task_spec_continuation',
  'invalid_task_spec_operation_id', 'invalid_task_spec_quality_goals', 'invalid_task_spec_write_scope', 'invalid_readonly_continuation',
  'invalid_review_continuation', 'invalid_implementation_continuation',
  'invalid_reconcile_operation', 'invalid_task_spec_reconciliation_decision', 'task_spec_unauthorized_change',
]);
const taskSpecFailureCodes = new Set(TASK_SPEC_FAILURE_CODES);
export const taskSpecFailureCode = value => {
  const code = typeof value === 'string' ? value : value?.code ?? value?.message;
  return taskSpecFailureCodes.has(code) ? code : null;
};
const SHA_OR_REF = /^[a-zA-Z0-9_./~^-]{1,160}$/;
// Priority areas are human-readable subject labels, not Git selectors or paths.
// Keep the pattern shared with the advertised JSON Schema so a valid prompt
// response cannot fail because a natural-language label contains spaces.
export const PRIORITY_AREA_PATTERN = '^[^\\s\\x00-\\x1F\\x7F](?:[^\\x00-\\x1F\\x7F]*[^\\s\\x00-\\x1F\\x7F])?$';
const priorityAreaPattern = new RegExp(PRIORITY_AREA_PATTERN, 'u');
const priorityArea = value => typeof value === 'string' && value.length <= 240 && priorityAreaPattern.test(value);
const ENUM = (v, values, name) => { if (!values.has(v)) throw new Error(`invalid_task_spec_${name}`); return v; };
const OBJECT = (v, name, keys) => {
  if (!v || typeof v !== 'object' || Array.isArray(v) || Object.keys(v).some(k => !keys.includes(k)))
    throw new Error(`invalid_task_spec_${name}`);
  return v;
};
const ref = (value) => typeof value === 'string' && SHA_OR_REF.test(value) &&
  !value.startsWith('-') && !value.includes('..') && !value.endsWith('.lock') && !value.includes('@{');
// Only canonical repository-relative paths are safe for exact post-write audit.
// A model-supplied ./private, private//file or mixed-case .GIT must not turn
// a restrictive selector/exclusion into an ineffective string comparison.
const path = canonicalTaskPath;

function validateSelectorCandidate(selector) {
  try { validateTaskSpec({...emptyTaskSpec('review'),target:{kind:'git',selector}}); return true; }
  catch { return false; }
}

export function validateTaskSpec(input, { modeOverride = null, planOnly = false } = {}) {
  const spec = OBJECT(input,'root',['version','operation','writeIntent','target','constraints','continuation','ambiguities','skillName','qualityGoals']);
  if (spec.version !== TASK_SPEC_VERSION) throw new Error('unsupported_task_spec_version');
  ENUM(spec.operation, OPERATIONS, 'operation');
  ENUM(spec.writeIntent, WRITE, 'write_intent');
  if (!Array.isArray(spec.ambiguities) || spec.ambiguities.length > 12 ||
    spec.ambiguities.some(a => typeof a !== 'string' || !a.trim() || a.length > 350)) throw new Error('invalid_task_spec_ambiguities');
  const target = OBJECT(spec.target,'target',['kind','selector']);
  if (!['none','git'].includes(target.kind)) throw new Error('invalid_task_spec_target_kind');
  if (target.kind === 'none' && target.selector !== null) throw new Error('invalid_task_spec_target_selector');
  if (target.kind === 'git') {
    const s = OBJECT(target.selector,'selector',['type','count','ref','left','right','notation','ticket','mergeParentIndex','selectors','paths']);
    ENUM(s.type, SELECTORS, 'selector_type');
    const required = {recent_commits:['count'],commit:['ref'],range:['left','right','notation'],relative_ref:['ref'],worktree:[],staged:[],unstaged:[],ticket_commits:['ticket'],files:['paths'],union:['selectors']}[s.type];
    if (Object.keys(s).some(k => k !== 'type' && k !== 'mergeParentIndex' && !required.includes(k)) ||
      required.some(k => s[k] === undefined)) throw new Error('invalid_task_spec_selector_fields');
    if (s.type === 'files' && (!Array.isArray(s.paths) || !s.paths.length || s.paths.length > 128 || s.paths.some(p => !path(p)) || new Set(s.paths).size !== s.paths.length)) throw new Error('invalid_explicit_file_paths');
    if (s.type === 'union' && (!Array.isArray(s.selectors) || s.selectors.length < 2 || s.selectors.length > 4 || s.selectors.some(item =>
      !item || typeof item !== 'object' || item.type === 'union' || !SELECTORS.has(item.type) ||
      Object.keys(item).some(k => !['type','count','ref','left','right','notation','ticket','mergeParentIndex','paths'].includes(k)) ||
      !validateSelectorCandidate(item)))) throw new Error('invalid_task_spec_union');
    if (s.type === 'recent_commits' && (!Number.isSafeInteger(s.count) || s.count < 1 || s.count > 128)) throw new Error('invalid_recent_commit_count');
    if (['commit','relative_ref'].includes(s.type) && !ref(s.ref)) throw new Error('invalid_task_spec_git_ref');
    if (s.type === 'range' && (!ref(s.left) || !ref(s.right) || !['..','...'].includes(s.notation))) throw new Error('invalid_task_spec_git_range');
    if (s.type === 'ticket_commits' && (typeof s.ticket !== 'string' || !/^[A-Z][A-Z0-9]{1,9}-\d{1,10}$/.test(s.ticket))) throw new Error('invalid_task_spec_ticket');
    if (s.type === 'union' && s.mergeParentIndex !== undefined) throw new Error('invalid_union_merge_parent');
    if (s.mergeParentIndex !== undefined && (!Number.isInteger(s.mergeParentIndex) || s.mergeParentIndex < 1 || s.mergeParentIndex > 16)) throw new Error('invalid_task_spec_merge_parent');
  }
  const c = OBJECT(spec.constraints,'constraints',['excludedPaths','reviewDepth','priorityAreas','resourcePreference','verification','reviewChecks','expectedFileCount','writeScope']);
  if (!Array.isArray(c.excludedPaths) || c.excludedPaths.length > 64 || c.excludedPaths.some(p => !path(p))) throw new Error('invalid_task_spec_exclusions');
  ENUM(c.reviewDepth, new Set(['unspecified','focused','standard','deep']), 'review_depth');
  ENUM(c.resourcePreference, new Set(['unspecified','efficient','thorough']), 'resources');
  ENUM(c.verification, new Set(['unspecified','required','not_requested']), 'verification');
  if (!Array.isArray(c.priorityAreas) || c.priorityAreas.length > 24 || c.priorityAreas.some(p => !priorityArea(p))) throw new Error('invalid_task_spec_priorities');
  if (c.reviewChecks !== undefined && (!Array.isArray(c.reviewChecks) || c.reviewChecks.length > 64 || c.reviewChecks.some(item =>
    !item || typeof item !== 'object' || Array.isArray(item) || Object.keys(item).some(key => !['kind','description'].includes(key)) ||
    !['step','acceptance'].includes(item.kind) || typeof item.description !== 'string' || !item.description.trim() || item.description.length > 500)))
    throw new Error('invalid_task_spec_review_checks');
  if (c.writeScope !== undefined && !['unspecified','tests_only','production_only','combined'].includes(c.writeScope))
    throw new Error('invalid_task_spec_write_scope');
  if (c.expectedFileCount !== undefined && (!Number.isSafeInteger(c.expectedFileCount) || c.expectedFileCount < 0 || c.expectedFileCount > 100000))
    throw new Error('invalid_task_spec_file_count');
  if (spec.qualityGoals !== undefined && (!Array.isArray(spec.qualityGoals) || spec.qualityGoals.length > QUALITY_GOALS.length ||
    new Set(spec.qualityGoals).size !== spec.qualityGoals.length || spec.qualityGoals.some(goal => !QUALITY_GOAL_SET.has(goal))))
    throw new Error('invalid_task_spec_quality_goals');
  if (spec.skillName !== undefined && (typeof spec.skillName !== 'string' || !/^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/.test(spec.skillName)))
    throw new Error('invalid_task_spec_skill');
  const continuation = OBJECT(spec.continuation,'continuation',['mode','operationId','decision']);
  ENUM(continuation.mode, CONTINUATIONS, 'continuation');
  if (continuation.operationId !== undefined && (typeof continuation.operationId !== 'string' || !/^[a-zA-Z0-9_-]{8,128}$/.test(continuation.operationId))) throw new Error('invalid_task_spec_operation_id');
  if (['information','revise_plan'].includes(spec.continuation.mode) &&
      (spec.operation === 'change' || spec.writeIntent === 'explicit')) throw new Error('invalid_readonly_continuation');
  if (['current_review','saved_review'].includes(spec.continuation.mode) && spec.operation !== 'review')
    throw new Error('invalid_review_continuation');
  if (['current_implementation','saved_implementation'].includes(spec.continuation.mode) &&
      (spec.operation !== 'change' || spec.writeIntent !== 'explicit')) throw new Error('invalid_implementation_continuation');
  if (spec.continuation.mode === 'reconcile' && (spec.operation !== 'investigate' || spec.writeIntent === 'explicit')) throw new Error('invalid_reconcile_operation');
  // Decisions are interpreted by the Router but executed only through a live,
  // state-bound gate after the exact Plan and checkout have been selected.
  if (continuation.decision !== undefined && (
      !['accept_checkout','decline'].includes(continuation.decision) ||
      !['reconcile','current_implementation','saved_implementation'].includes(continuation.mode)))
    throw new Error('invalid_task_spec_reconciliation_decision');
  if (spec.writeIntent !== 'explicit' && spec.operation === 'change') throw new Error('task_spec_unauthorized_change');
  if (spec.operation !== 'review' && target.kind === 'git' && ['current_review','saved_review'].includes(continuation.mode)) throw new Error('invalid_task_spec_continuation');
  // A model classification cannot override host commands. Host constraints are
  // narrower than model claims; skill content is not a host permission signal.
  const forcedOperation = planOnly ? 'plan' : modeOverride;
  const operation = forcedOperation ?? spec.operation;
  const writeIntent = planOnly || ['review','investigate','plan'].includes(operation) ? 'not_requested'
    : modeOverride === 'change' ? 'explicit' : spec.writeIntent;
  return { ...spec, operation, writeIntent, ambiguities:[...spec.ambiguities], qualityGoals:[...(spec.qualityGoals ?? [])],
    target:{ ...target, selector:target.selector ? { ...target.selector } : null },
    constraints:{...c,excludedPaths:[...new Set(c.excludedPaths)],priorityAreas:[...new Set(c.priorityAreas)],
      ...(c.reviewChecks ? {reviewChecks:c.reviewChecks.map(item=>({...item}))} : {})},
    continuation:{...continuation} };
}

export const emptyTaskSpec = (operation = 'investigate', writeIntent = 'not_requested') => ({
  version: 1, operation, writeIntent, qualityGoals:[], target:{kind:'none',selector:null},
  constraints:{excludedPaths:[],reviewDepth:'unspecified',priorityAreas:[],resourcePreference:'unspecified',verification:'unspecified'},
  continuation:{mode:'new'},ambiguities:[],
});

export function structuredCommandSelector(reviewTarget) {
  if (!reviewTarget || reviewTarget.type !== 'commit') return null;
  return {type:'commit',ref:reviewTarget.revision,...(reviewTarget.mergeParentIndex ? {mergeParentIndex:reviewTarget.mergeParentIndex}:{})};
}
